import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const data=readFileSync(new URL('../public/assets/characters/Qwerty_Rigged.glb',import.meta.url));
const size=data.readUInt32LE(8),jlen=data.readUInt32LE(12);
const gltf=JSON.parse(data.subarray(20,20+jlen).toString('utf8'));
test('Qwerty binary glTF is self-contained and skeletal, with UVs and skin weights',()=>{
  assert.equal(data.subarray(0,4).toString(),'glTF');
  assert.equal(size,data.length);
  assert.equal(gltf.skins[0].joints.length,19);
  assert.ok(gltf.meshes[0].primitives.every(p=>p.attributes.TEXCOORD_0!==undefined&&p.attributes.JOINTS_0!==undefined&&p.attributes.WEIGHTS_0!==undefined));
  assert.deepEqual(new Set(gltf.animations.map(x=>x.name)),new Set(['Qwerty_Talk_Flap','Qwerty_Walk','Qwerty_Idle','Qwerty_Suspicious_Lids']));
  assert.ok(gltf.nodes.some(n=>n.name==='eyelidL'));
  assert.ok(gltf.nodes.some(n=>n.name==='eyelidR'));
  assert.ok(gltf.nodes.some(n=>n.name==='skull_upper'));
  assert.ok(gltf.nodes.some(n=>n.name==='base_plate'));
  assert.ok(!gltf.nodes.some(n=>n.name==='jaw_lower'));
  const base=gltf.nodes.find(n=>n.name==='base_plate');
  assert.ok(base.children.includes(gltf.nodes.findIndex(n=>n.name==='skull_upper')));
});
test('emissive white 2D graphic is distinct from facial lids and kill color is runtime-controlled',()=>{
  const i=gltf.materials.findIndex(m=>m.name==='Qwerty/Eyes_2D_Emission');
  assert.ok(i>=0);
  assert.deepEqual(gltf.materials[i].emissiveFactor,[1,1,1]);
  assert.equal(gltf.materials[i].pbrMetallicRoughness.baseColorTexture,undefined);
  const src=readFileSync(new URL('../public/world3d.js',import.meta.url),'utf8');
  assert.match(src,/new GLTFLoader\(\)\.loadAsync/);
  const toon=readFileSync(new URL('../public/cel-robots.js',import.meta.url),'utf8');
  assert.match(toon,/Eyes_2D_Emission/);
  const motion=readFileSync(new URL('../public/qwerty-motion.js',import.meta.url),'utf8');
  assert.match(src,/createQwertyMotionRig\(gltf\)/);
  assert.match(motion,/celShadeRobot\(root,'Qwerty'\)/);
  assert.match(motion,/eyes\[0\]\.color\.set\(killMode\?'#ff1616':'#ffffff'\)/);
  assert.match(src,/for\(const child of legacy\)child\.visible=false/);
  assert.match(src,/canvas\.dataset\.qwertyModel='glb-q16'/);
  assert.match(src,/a\.setLids\(/);
  assert.match(src,/a\.setSpeaking\(/);
  const model=readFileSync(new URL('../public/assets/characters/Qwerty_Q16_Validated.glb',import.meta.url));
  assert.equal(model.subarray(0,4).toString(),'glTF');
  const document=JSON.parse(model.subarray(20,20+model.readUInt32LE(12)).toString('utf8'));
  assert.equal(document.animations.length,6);
  assert.equal(document.skins[0].joints.length,19);
  assert.ok(document.meshes[0].primitives.every(p=>p.attributes.TEXCOORD_0!==undefined&&p.attributes.JOINTS_0!==undefined));
});
